"""Summary numbers for the rewritten US-cut memo that are not produced by code/68-76 directly.

Reads output tables from 69 and 75 and writes output/us_cut_memo/numbers_sum.tex:
  - reduced-form 95% intervals for aid dependence (per s.d.) on wasting, severe wasting, death rates
  - national food and cash reach, January-June 2024 vs 2025 (per month and per 100 residents)
  - change in sites offering severe-malnutrition treatment, 2024 vs 2025
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TAB = ROOT / "output" / "tables"
M = {}
f1 = lambda v: f"{v:.1f}"
f2 = lambda v: f"{v:.2f}"

R = pd.read_csv(TAB / "som_aiddep_did.csv")
R = R[(R.season_fe == "common") & (R.exposure == "z_index")].set_index("outcome")
for y, t in [("gam", "Gam"), ("sam", "Sam"), ("cdr", "Cdr"), ("u5dr", "Ufive")]:
    b, se = R.loc[y, "b"], R.loc[y, "se"]
    M[f"sumIdx{t}"], M[f"sumIdx{t}Lo"], M[f"sumIdx{t}Hi"] = f2(b), f2(b - 1.96 * se), f2(b + 1.96 * se)
    M[f"sumIdx{t}Mean"] = f2(R.loc[y, "ymean_pre"])

D = pd.read_csv(TAB / "som_dlv_districts.csv")
a, b, pop = D.fsc_gu2024.sum(), D.fsc_gu2025.sum(), D["pop"].sum()
M["sumFscHaTf"], M["sumFscHaTv"] = f1(a / 1e6), f1(b / 1e6)
M["sumFscHaTfPc"], M["sumFscHaTvPc"] = f1(a / pop * 100), f1(b / pop * 100)
M["sumFscHaDrop"] = f"{100 * (1 - b / a):.0f}"

nut = pd.read_csv(TAB / "som_dlv_districts.csv")
num = ROOT / "output" / "us_cut_memo" / "numbers_dlv.tex"
vals = dict(l.split("}{", 1) for l in num.read_text().splitlines() if l.startswith("\\newcommand"))
tf = float(vals["\\newcommand{\\ndvOtpTf"].rstrip("}"))
tv = float(vals["\\newcommand{\\ndvOtpTv"].rstrip("}"))
M["sumOtpDrop"] = f"{100 * (1 - tv / tf):.0f}"

# second year: treatment sites and food/cash reach, Jan-Jun 2026 vs Jan-Jun 2024, by exposure
import importlib.util
import numpy as np
spec = importlib.util.spec_from_file_location("m75", ROOT / "code" / "75_somalia_delivery.py")
M75 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M75)
N, F, X = M75.nutrition(), M75.fsc(), M75.district_frame()
h1 = N[N.m.between(1, 6)]
nat = h1.groupby("year").otp_sites.sum() / h1.groupby("year").m.nunique()
M["sumOtpHaTf"], M["sumOtpHaTs"] = f"{nat[2024]:.0f}", f"{nat[2026]:.0f}"
M["sumOtpHaDropTs"] = f"{100 * (1 - nat[2026] / nat[2024]):.0f}"
w = h1.groupby(["dist", "year"]).otp_sites.mean().unstack()
fh = F[F.m.between(1, 6)].groupby(["dist", "year"]).fsc.mean().unstack()
fnat = F[F.m.between(1, 6)].groupby("year").fsc.sum() / 6
M["sumFscHaTs"] = f1(fnat[2026] / 1e6)
D = X.copy()
D["otp_loss26"] = (w.get(2024).reindex(D.index).fillna(0) - w.get(2026).reindex(D.index).fillna(0)) / (D["pop"] * 0.19) * 1e4
D["fsc_loss26"] = (fh.get(2024).reindex(D.index).fillna(0) - fh.get(2026).reindex(D.index).fillna(0)) / D["pop"] * 100
for y in [2025, 2026]:   # proportional food-and-cash loss, Jan-Jun vs Jan-Jun 2024 (minus log change)
    D[f"fsc_log{y % 100}"] = -(np.log(fh.get(y).reindex(D.index).fillna(0) + 100) - np.log(fh.get(2024).reindex(D.index).fillna(0) + 100))
M["sumCorrIdxUs"] = f2(D["index"].corr(D.E_pred))
for x, xt in [("otp_loss26", "Otp"), ("fsc_loss26", "Fsc"), ("fsc_log25", "FscGTv"), ("fsc_log26", "FscG")]:
    for z, zt in [("index", "Idx"), ("E_pred", "Us")]:
        d = D.dropna(subset=[x, z])
        A = np.column_stack([np.ones(len(d)), d[z]])
        b_, V = M75.M71.cl_ols(d[x].values, A, d.region.values)
        M[f"sumF{xt}{zt}Ts"] = f1(b_[1] ** 2 / V[1, 1])
        M[f"sumBsd{xt}{zt}Ts"] = f2(b_[1] * d[z].std())

(ROOT / "output" / "us_cut_memo" / "numbers_sum.tex").write_text(
    "% generated by code/78_us_cut_summary.py -- do not edit\n" +
    "".join(f"\\newcommand{{\\n{k}}}{{{v}}}\n" for k, v in M.items()))
print(M)
